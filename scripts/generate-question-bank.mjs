function assertClean(question) {
  const lower = question.toLowerCase();
  const glued = lower.match(/met de letter \{l\}\s+(?!begint\.?$)([^.]+)/);
  if (glued && glued[1].trim()) {
    throw new Error(`Invalid suffix glued after letter placeholder: ${question}`);
  }
}

