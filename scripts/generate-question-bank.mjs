function buildLetterCategory(categoryId) {
  const stems = CATEGORY_STEMS[categoryId];
  if (!stems?.length) throw new Error(`Missing stems for ${categoryId}`);
  const questions = [];
  const seen = new Set();
  for (const stem of stems) {
    for (const pattern of LETTER_PATTERNS) {
      const question = finishQuestion(pattern(stem));
      assertClean(question);
      const norm = question.toLowerCase();
      if (seen.has(norm)) continue;
      seen.add(norm);
      questions.push(question);
      if (questions.length >= QUESTIONS_PER_CATEGORY) break;
    }
    if (questions.length >= QUESTIONS_PER_CATEGORY) break;
  }
  if (questions.length < QUESTIONS_PER_CATEGORY) {
    throw new Error(
      `Category ${categoryId} only ${questions.length} unique questions (need ${QUESTIONS_PER_CATEGORY}). Add stems or patterns.`
    );
  }
  return questions.slice(0, QUESTIONS_PER_CATEGORY).map((question, i) => ({
    id: `${categoryId}_${String(i + 1).padStart(3, "0")}`,
    categoryId,
    question,
    usesLetter: true,
    active: true,
  }));
}

function buildGek() {
  const items = [];
  const seen = new Set();

  for (const raw of GEK_NO_LETTER) {
    const question = finishQuestion(raw);
    assertClean(question);
    const norm = question.toLowerCase();
    if (seen.has(norm)) continue;
    seen.add(norm);
    items.push({
      id: `gek_nl_${String(items.length + 1).padStart(3, "0")}`,
      categoryId: "gek",
      question,
      usesLetter: false,
      active: true,
    });
    if (items.length >= QUESTIONS_PER_CATEGORY) return items;
  }

  for (const stem of GEK_LETTER_STEMS) {
    for (const pattern of LETTER_PATTERNS) {
      const question = finishQuestion(pattern(stem));
      assertClean(question);
      const norm = question.toLowerCase();
      if (seen.has(norm)) continue;
      seen.add(norm);
      items.push({
        id: `gek_${String(items.length + 1).padStart(3, "0")}`,
        categoryId: "gek",
        question,
        usesLetter: true,
        active: true,
      });
      if (items.length >= QUESTIONS_PER_CATEGORY) return items;
    }
  }
  throw new Error(`gek only ${items.length} questions`);
}

const bank = [];
const seenText = new Set();
const seenId = new Set();

for (const cat of CATEGORIES) {
  const items = cat.id === "gek" ? buildGek() : buildLetterCategory(cat.id);
  for (const q of items) {
    if (!VALID_IDS.has(q.categoryId)) throw new Error("bad categoryId " + q.categoryId);
    if (seenId.has(q.id)) throw new Error("dup id " + q.id);
    const norm = q.categoryId + "\u001f" + q.question.toLowerCase().trim();
    if (seenText.has(norm)) throw new Error("dup text in bank: " + q.id);
    seenId.add(q.id);
    seenText.add(norm);
    bank.push(q);
  }
}

